# --- 2. PLOTTING ENGINE ---

def plot_per_class(nested_dict, title):
    fig, axes = plt.subplots(2, 4, figsize=(18, 10))
    axes = axes.flatten()
    sorted_keys = ["1A", "1B", "2Peso", "5A", "5B", "10A", "10B", "20A"]
    
    for i, coin in enumerate(sorted_keys):
        ax = axes[i]
        raw_list = []
        if coin in nested_dict:
            for group_list in nested_dict[coin]:
                raw_list.extend(group_list)
        
        if not raw_list:
            ax.text(0.5, 0.5, "NO DATA", ha='center', va='center', color='#444b5a')
            ax.set_title(f"Class {coin}", color='#444b5a')
            continue

        h_arr = np.array(raw_list)
        h_cum = np.cumsum(h_arr)
        t_cum = np.cumsum(1 - h_arr)
        
        total = len(h_arr)
        final_h = h_cum[-1]
        final_t = t_cum[-1]
        h_pct = (final_h / total) * 100
        t_pct = (final_t / total) * 100

        # Restored the detailed legend logic
        ax.plot(h_cum, color=color_heads, linewidth=1.8, label=f"Heads: {final_h} ({h_pct:.1f}%)")
        ax.plot(t_cum, color=color_tails, linewidth=1.8, label=f"Tails: {final_t} ({t_pct:.1f}%)")
        ax.plot([], [], color='none', label=f"Total: {total} (100%)")
        
        ax.scatter(total-1, final_h, color=color_heads, s=20, zorder=5)
        ax.scatter(total-1, final_t, color=color_tails, s=20, zorder=5)
        
        ax.set_title(f"Class {coin}", fontsize=11, fontweight='bold', pad=10)
        ax.set_xlim(0, total + 5)
        ax.set_ylim(0, max(final_h, final_t) + 15)
        ax.grid(True, alpha=0.1)
        ax.legend(loc='upper left', frameon=True, facecolor='#1a222f', 
                  edgecolor=color_grid, prop={'size': 7}, labelspacing=0.4)

    plt.suptitle(title, fontsize=18, fontweight='bold', y=0.98)
    plt.tight_layout(rect=[0, 0.03, 1, 0.95], h_pad=3.5, w_pad=2.5)
    plt.show()

def plot_final_combined(table_dict, tiles_dict):
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(18, 8))
    
    # Flatten all data for surface totals
    table_raw = [val for sublist in table_dict.values() for item in sublist for val in item]
    tiles_raw = [val for sublist in tiles_dict.values() for item in sublist for val in item]

    for ax, data, title in zip([ax1, ax2], [table_raw, tiles_raw], ["TOTAL TABLE (G1-G8)", "TOTAL TILES (G9-G15)"]):
        h_arr = np.array(data)
        h_cum = np.cumsum(h_arr)
        t_cum = np.cumsum(1 - h_arr)
        total, final_h, final_t = len(data), h_cum[-1], t_cum[-1]
        
        ax.plot(h_cum, color=color_heads, linewidth=2.5, label=f"Total Heads: {final_h} ({final_h/total*100:.1f}%)")
        ax.plot(t_cum, color=color_tails, linewidth=2.5, label=f"Total Tails: {final_t} ({final_t/total*100:.1f}%)")
        ax.plot([], [], color='none', label=f"Grand Total: {total}")
        
        ax.set_title(title, fontsize=14, fontweight='bold', pad=15)
        ax.set_xlabel("Total Combined")
        ax.set_ylabel("Cumulative Count")
        ax.legend(facecolor='#1a222f', edgecolor=color_grid, fontsize=10)
        ax.grid(True, alpha=0.1)

    plt.suptitle("CANVAS H & T (COMBINED SURFACE TOTALS)", fontsize=20, fontweight='bold', y=0.96)
    plt.tight_layout(rect=[0, 0.03, 1, 0.90])
